#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# x86-only integration test with dummy Arch package archives and a disposable key.
set -euo pipefail

root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)
tool=$root/tools/omamobile-localrepo
machine=$(uname -m)
[[ $machine == x86_64 || $machine == amd64 ]] || {
  printf 'localrepo test requires an x86_64 host; got %s\n' "$machine" >&2
  exit 1
}
for command_name in gpg repo-add repo-remove bsdtar; do
  command -v "$command_name" >/dev/null 2>&1 || {
    printf 'localrepo test requires %s\n' "$command_name" >&2
    exit 1
  }
done

T=$(mktemp -d)
trap 'rm -rf -- "$T"' EXIT
export OMAMOBILE_LOCALREPO_ROOT=$T/repo
export OMAMOBILE_LOCALREPO_GNUPGHOME=$T/gnupg
mkdir -m 700 "$OMAMOBILE_LOCALREPO_GNUPGHOME" "$T/package-root" "$T/out"
gpg --homedir "$OMAMOBILE_LOCALREPO_GNUPGHOME" --batch \
  --pinentry-mode loopback --passphrase '' \
  --quick-generate-key 'omamobile localrepo disposable test key' ed25519 sign 0 >/dev/null 2>&1
export OMAMOBILE_LOCALREPO_KEY
OMAMOBILE_LOCALREPO_KEY=$(gpg --homedir "$OMAMOBILE_LOCALREPO_GNUPGHOME" \
  --with-colons --list-secret-keys | awk -F: '$1 == "fpr" { print $10; exit }')
# The fake ambient GPG home proves repo-add uses the configured dedicated home.
mkdir -m 700 "$T/ambient-gnupg"
export GNUPGHOME=$T/ambient-gnupg
[[ -n $OMAMOBILE_LOCALREPO_KEY ]] || { echo 'test key fingerprint missing' >&2; exit 1; }
public_key=$T/omamobile-localrepo.pub
"$tool" export-key "$OMAMOBILE_LOCALREPO_KEY" "$public_key"
gpg --show-keys "$public_key" >/dev/null
grep -q '^-----BEGIN PGP PUBLIC KEY BLOCK-----$' "$public_key"
if grep -q 'PRIVATE KEY BLOCK' "$public_key"; then
  echo 'public-key export unexpectedly contains private material' >&2
  exit 1
fi

make_dummy_package() {
  local name=$1 version=$2 arch=$3
  local package=$T/out/$name-$version-$arch.pkg.tar
  local package_root=$T/package-root/$name
  mkdir -p "$package_root"
  cat > "$package_root/.PKGINFO" <<EOF_PKGINFO
# Generated by tests/localrepo.sh
pkgname = $name
pkgbase = $name
pkgver = $version
pkgdesc = Disposable x86 repository test fixture
url = https://example.invalid/
builddate = 1
packager = Test Fixture <nobody@example.invalid>
size = 0
arch = $arch
license = MIT
EOF_PKGINFO
  bsdtar -cf "$package" -C "$package_root" .PKGINFO
  printf '%s\n' "$package"
}

packages=()
while IFS='|' read -r name arch version _; do
  [[ -n $name && $name != \#* ]] || continue
  packages+=("$(make_dummy_package "$name" "$version" "$arch")")
done < "$root/tools/omamobile-localrepo-packages.tsv"

"$tool" init >/dev/null
"$tool" add "${packages[@]}"
"$tool" verify

db=$OMAMOBILE_LOCALREPO_ROOT/aarch64/omamobile-local.db.tar.zst
[[ -s $db && -s $db.sig ]] || { echo 'signed repository database missing' >&2; exit 1; }
gpg --homedir "$OMAMOBILE_LOCALREPO_GNUPGHOME" --verify "$db.sig" "$db" >/dev/null
for package in "$OMAMOBILE_LOCALREPO_ROOT"/aarch64/*.pkg.tar; do
  [[ -s $package.sig ]] || { echo "package signature missing: $package" >&2; exit 1; }
  gpg --homedir "$OMAMOBILE_LOCALREPO_GNUPGHOME" --verify "$package.sig" "$package" >/dev/null
done
while IFS= read -r entry; do
  bsdtar -xOf "$db" "$entry" | grep -q '^%PGPSIG%$' || {
    echo "repo-add did not embed the package signature in $entry" >&2
    exit 1
  }
done < <(bsdtar -tf "$db" | awk '/\/desc$/')

"$tool" add "${packages[5]}"
"$tool" remove omamobile-device-instantnoodlep
if compgen -G "$OMAMOBILE_LOCALREPO_ROOT/aarch64/omamobile-device-instantnoodlep-*.pkg.tar*" >/dev/null; then
  echo 'removed package archive or signature sidecar remains' >&2
  exit 1
fi
"$tool" verify
"$tool" add "${packages[5]}"
"$tool" verify

bad_package=$(make_dummy_package mesa 1:26.2.4-1.6 aarch64)
if "$tool" add "$bad_package" >/dev/null 2>&1; then
  echo 'package outside the version contract unexpectedly passed' >&2
  exit 1
fi
"$tool" pacman-conf | grep -q '^SigLevel = Required TrustedOnly$'
"$tool" pacman-conf | grep -Fqx "Server = file:///var/lib/omamobile/localrepo/\$arch"

printf '%s\n' 'ok - x86 dummy packages were signed, indexed, verified, removed, and re-added'
